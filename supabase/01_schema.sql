create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  full_name   text        not null,
  email       text,                                   -- contact email (NULL for Instagram accounts)
  provider    public.auth_provider not null default 'email',
  provider_id text        not null,                   -- email / gmail / instagram username
  phone       text,
  address     text,
  role        public.user_role not null default 'customer',
  created_at  timestamptz not null default now(),
  -- "Sign Up creates an account only once" - per provider + identifier
  constraint profiles_provider_id_key unique (provider, provider_id),
  -- Same format rules as the site: Facebook = Gmail, Instagram = username, Email = email
  constraint profiles_provider_id_format check (
       (provider = 'email'     and provider_id ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$')
    or (provider = 'facebook'  and provider_id ~ '^[a-z0-9](?:[a-z0-9._+-]*[a-z0-9])?@gmail\.com$')
    or (provider = 'instagram' and provider_id ~ '^(?!\.)(?!.*\.\.)(?!.*\.$)[a-z0-9._]{1,30}$')
  )
);

