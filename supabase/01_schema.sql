-- ---------------------------------------------------------------------
-- Login identity mapping
-- Supabase Auth signs people in with an email + password. The site has three
-- SEPARATE account types (Email, Facebook=Gmail, Instagram=username), so each
-- one is mapped to a unique internal auth email. The same function is mirrored
-- in assets/js/db.js (authEmailFor) - keep both identical.
--   email     name@example.com   -> name@example.com
--   facebook  name@gmail.com     -> name_at_gmail.com@facebook.local
--   instagram my.user            -> my.user@instagram.local
-- ---------------------------------------------------------------------
create function public.auth_email_for(p_provider public.auth_provider, p_id text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case p_provider
    when 'email'     then lower(p_id)
    when 'facebook'  then replace(lower(p_id), '@', '_at_') || '@facebook.local'
    when 'instagram' then lower(p_id) || '@instagram.local'
  end;
$$;

