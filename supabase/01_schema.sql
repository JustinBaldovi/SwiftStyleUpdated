-- Is the current signed-in user an admin? (SECURITY DEFINER so RLS policies can call it without recursion)
create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

-- Create the profile automatically whenever someone signs up through Supabase Auth.
-- The browser passes full_name / provider / provider_id as sign-up metadata.
-- NOTE: `role` is never read from metadata - everyone starts as 'customer'.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  meta       jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  v_provider public.auth_provider;
  v_id       text;
begin
  begin
    v_provider := coalesce(nullif(meta->>'provider', ''), 'email')::public.auth_provider;
  exception when invalid_text_representation then
    v_provider := 'email';
  end;

  if v_provider = 'email' then
    v_id := lower(new.email);
  else
    v_id := lower(regexp_replace(coalesce(meta->>'provider_id', ''), '^@', ''));
  end if;

  -- the internal auth email must match the identity being claimed
  if new.email is distinct from public.auth_email_for(v_provider, v_id) then
    raise exception 'Sign-up identity does not match the auth email.' using errcode = '22023';
  end if;

  insert into public.profiles (id, full_name, email, provider, provider_id, phone, address)
  values (
    new.id,
    coalesce(nullif(trim(meta->>'full_name'), ''), split_part(v_id, '@', 1)),
    case when v_provider = 'instagram' then null else v_id end,
    v_provider,
    v_id,
    nullif(trim(meta->>'phone'), ''),
    nullif(trim(meta->>'address'), '')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Cart rule from cart_action.php: quantity can never exceed stock.
create function public.cart_clamp_quantity()
returns trigger
language plpgsql
set search_path = ''
as $$
declare v_stock integer;
begin
  select stock into v_stock from public.products where product_id = new.product_id;
  if v_stock is null or v_stock <= 0 then
    raise exception 'This item is out of stock.' using errcode = '23514';
  end if;
  new.quantity := least(greatest(new.quantity, 1), v_stock);
  return new;
end;
$$;

create trigger cart_clamp_quantity_trg
  before insert or update of quantity, product_id on public.cart
  for each row execute function public.cart_clamp_quantity();

-- Checkout (replaces process_checkout.php). One transaction: creates the order,
-- copies cart lines into order_items using DB prices, deducts stock, empties the cart.
-- Returns the new order_id. Any problem (e.g. not enough stock) rolls everything back.
create function public.place_order(
  p_full_name      text,
  p_email          text,
  p_phone          text,
  p_address        text,
  p_payment_method public.payment_method_type default 'COD'
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid      uuid := (select auth.uid());
  v_order_id bigint;
  v_total    numeric(10,2);
  r          record;
begin
  if v_uid is null then
    raise exception 'You must be signed in to place an order.' using errcode = '28000';
  end if;
  if coalesce(trim(p_full_name), '') = '' or coalesce(trim(p_email), '') = ''
     or coalesce(trim(p_phone), '') = '' or coalesce(trim(p_address), '') = '' then
    raise exception 'Please complete all shipping information fields.' using errcode = '22023';
  end if;

  select sum(p.price * c.quantity) into v_total
  from public.cart c join public.products p on p.product_id = c.product_id
  where c.user_id = v_uid;

  if v_total is null then
    raise exception 'Your cart is empty.' using errcode = '22023';
  end if;

  insert into public.orders (user_id, full_name, email, phone, address, payment_method, total_amount, order_status)
  values (v_uid, trim(p_full_name), trim(p_email), trim(p_phone), trim(p_address), p_payment_method, v_total, 'Pending')
  returning order_id into v_order_id;

  for r in
    select c.product_id, c.color, c.quantity, p.product_name, p.price
    from public.cart c join public.products p on p.product_id = c.product_id
    where c.user_id = v_uid
    order by c.cart_id
  loop
    -- atomic stock deduction; fails (and rolls back the whole order) if stock ran out
    update public.products set stock = stock - r.quantity
    where product_id = r.product_id and stock >= r.quantity;
    if not found then
      raise exception 'Not enough stock for "%".', r.product_name using errcode = '23514';
    end if;

    insert into public.order_items (order_id, product_id, product_name, color, quantity, price, subtotal)
    values (v_order_id, r.product_id, r.product_name, nullif(r.color, ''), r.quantity, r.price, r.price * r.quantity);
  end loop;

  delete from public.cart where user_id = v_uid;
  return v_order_id;
end;
$$;

-- Admin dashboard numbers (replaces the 4 COUNT/SUM queries in admin/dashboard.php)
create function public.admin_dashboard_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Admins only.' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'total_products',  (select count(*) from public.products),
    'total_orders',    (select count(*) from public.orders),
    'total_customers', (select count(*) from public.profiles where role = 'customer'),
    'total_revenue',   (select coalesce(sum(total_amount), 0) from public.orders where order_status <> 'Cancelled')
  );
end;
$$;

