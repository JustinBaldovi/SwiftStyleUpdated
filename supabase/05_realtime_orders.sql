-- Enable realtime order INSERT/UPDATE events for the customer and owner dashboards.
-- Row Level Security on public.orders still determines which rows each subscriber can see.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'orders'
  ) then
    alter publication supabase_realtime add table public.orders;
  end if;
end
$$;
