-- Product inventory images and customer reviews.
-- Run after 01_schema.sql through 08_fix_admin_order_delete_permissions.sql.
begin;

alter table public.products enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_product_id_seq to authenticated;

create table if not exists public.product_reviews (
  review_id bigint generated by default as identity primary key,
  product_id integer not null
    constraint product_reviews_product_id_fkey
    references public.products (product_id) on delete cascade,
  user_id uuid not null
    constraint product_reviews_user_id_fkey
    references public.profiles (id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text not null check (char_length(btrim(comment)) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint product_reviews_one_per_customer unique (product_id, user_id)
);

create index if not exists product_reviews_product_created_idx
  on public.product_reviews (product_id, created_at desc);

alter table public.product_reviews enable row level security;
revoke all privileges on public.product_reviews from public, anon, authenticated;
revoke all privileges on sequence public.product_reviews_review_id_seq from public, anon, authenticated;

drop policy if exists product_reviews_read on public.product_reviews;
create policy product_reviews_read on public.product_reviews
  for select to authenticated using (true);

drop policy if exists product_reviews_insert_own on public.product_reviews;
create policy product_reviews_insert_own on public.product_reviews
  for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists product_reviews_update_own on public.product_reviews;
create policy product_reviews_update_own on public.product_reviews
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

grant select, insert on public.product_reviews to authenticated;
grant update (product_id, user_id, rating, comment) on public.product_reviews to authenticated;
grant usage, select on sequence public.product_reviews_review_id_seq to authenticated;

insert into storage.buckets (id, name, "public", file_size_limit, allowed_mime_types)
values (
  'product-images',
  'product-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set "public" = excluded."public",
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists product_images_public_read on storage.objects;
create policy product_images_public_read on storage.objects
  for select to anon, authenticated
  using (bucket_id = 'product-images');

drop policy if exists product_images_admin_insert on storage.objects;
create policy product_images_admin_insert on storage.objects
  for insert to authenticated
  with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists product_images_admin_update on storage.objects;
create policy product_images_admin_update on storage.objects
  for update to authenticated
  using (bucket_id = 'product-images' and public.is_admin())
  with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists product_images_admin_delete on storage.objects;
create policy product_images_admin_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'product-images' and public.is_admin());

do $$
declare
  target_table text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach target_table in array array['products', 'product_reviews']
    loop
      if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = target_table
      ) then
        execute format('alter publication supabase_realtime add table public.%I', target_table);
      end if;
    end loop;
  end if;
end
$$;

commit;
