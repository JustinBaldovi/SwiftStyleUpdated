-- Let each signed-in customer save up to five reusable checkout addresses.
-- Run after 01_schema.sql. Safe to rerun.
begin;

create table if not exists public.saved_addresses (
  address_id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  label text not null check (length(trim(label)) between 1 and 40),
  address text not null check (length(trim(address)) between 1 and 250),
  city text not null check (length(trim(city)) between 1 and 100),
  province text not null check (length(trim(province)) between 1 and 100),
  postal_code text not null check (postal_code ~ '^[0-9]{4}$'),
  delivery_note text not null default '' check (length(trim(delivery_note)) <= 500),
  created_at timestamptz not null default now()
);

alter table public.saved_addresses enable row level security;

drop policy if exists saved_addresses_select_own on public.saved_addresses;
create policy saved_addresses_select_own
  on public.saved_addresses for select to authenticated
  using (user_id = (select auth.uid()));

revoke all on table public.saved_addresses from public, anon, authenticated;
grant select on table public.saved_addresses to authenticated;

create or replace function public.save_my_address(
  p_address_id bigint,
  p_label text,
  p_address text,
  p_city text,
  p_province text,
  p_postal_code text,
  p_delivery_note text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_address_id bigint;
begin
  if v_uid is null then
    raise exception 'You must be signed in to save an address.' using errcode = '28000';
  end if;

  if coalesce(length(trim(p_label)), 0) not between 1 and 40
     or coalesce(length(trim(p_address)), 0) not between 1 and 250
     or coalesce(length(trim(p_city)), 0) not between 1 and 100
     or coalesce(length(trim(p_province)), 0) not between 1 and 100
     or coalesce(trim(p_postal_code), '') !~ '^[0-9]{4}$'
     or length(trim(coalesce(p_delivery_note, ''))) > 500 then
    raise exception 'Enter a label and complete address with a 4-digit postal code.' using errcode = '22023';
  end if;

  if p_address_id is not null then
    update public.saved_addresses
    set label = trim(p_label),
        address = trim(p_address),
        city = trim(p_city),
        province = trim(p_province),
        postal_code = trim(p_postal_code),
        delivery_note = trim(coalesce(p_delivery_note, ''))
    where address_id = p_address_id and user_id = v_uid
    returning address_id into v_address_id;

    if v_address_id is null then
      raise exception 'Saved address not found.' using errcode = '22023';
    end if;
    return v_address_id;
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(v_uid::text));
  if (select count(*) from public.saved_addresses where user_id = v_uid) >= 5 then
    raise exception 'You can save up to five addresses. Delete one before adding another.' using errcode = '22023';
  end if;

  insert into public.saved_addresses (user_id, label, address, city, province, postal_code, delivery_note)
  values (v_uid, trim(p_label), trim(p_address), trim(p_city), trim(p_province),
          trim(p_postal_code), trim(coalesce(p_delivery_note, '')))
  returning address_id into v_address_id;
  return v_address_id;
end;
$$;

create or replace function public.delete_my_saved_address(p_address_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null then
    raise exception 'You must be signed in to delete a saved address.' using errcode = '28000';
  end if;

  delete from public.saved_addresses
  where address_id = p_address_id and user_id = v_uid;
  return found;
end;
$$;

revoke all on function public.save_my_address(bigint, text, text, text, text, text, text) from public, anon;
revoke all on function public.delete_my_saved_address(bigint) from public, anon;
grant execute on function public.save_my_address(bigint, text, text, text, text, text, text) to authenticated;
grant execute on function public.delete_my_saved_address(bigint) to authenticated;

notify pgrst, 'reload schema';

commit;
