-- Customer support inbox, owner replies, one-time response ratings, and notifications.
-- Run after 09_authenticated_permissions_with_rls.sql. Safe to rerun.
begin;

grant usage on schema public to authenticated;

create table if not exists public.support_messages (
  message_id bigint generated by default as identity primary key,
  user_id uuid not null
    constraint support_messages_user_id_fkey references public.profiles (id) on delete cascade,
  customer_name text not null,
  customer_email text,
  subject text not null check (char_length(btrim(subject)) between 1 and 160),
  message text not null check (char_length(btrim(message)) between 1 and 5000),
  created_at timestamptz not null default now(),
  owner_reply text,
  owner_replied_at timestamptz,
  reply_seen_at timestamptz,
  rating smallint check (rating between 1 and 5),
  rated_at timestamptz,
  constraint support_messages_reply_length
    check (owner_reply is null or char_length(btrim(owner_reply)) between 1 and 5000),
  constraint support_messages_reply_rating
    check (rating is null or (owner_reply is not null and reply_seen_at is not null and rated_at is not null))
);

create index if not exists support_messages_user_created_idx
  on public.support_messages (user_id, created_at desc);
create index if not exists support_messages_created_idx
  on public.support_messages (created_at desc);

alter table public.support_messages enable row level security;
revoke all privileges on public.support_messages from public, anon, authenticated;
revoke all privileges on sequence public.support_messages_message_id_seq from public, anon, authenticated;

drop policy if exists support_messages_read on public.support_messages;
create policy support_messages_read on public.support_messages
  for select to authenticated
  using (user_id = (select auth.uid()) or public.is_admin());

drop policy if exists support_messages_insert_own on public.support_messages;
create policy support_messages_insert_own on public.support_messages
  for insert to authenticated
  with check (user_id = (select auth.uid()) and not public.is_admin());

drop policy if exists support_messages_update_own on public.support_messages;
create policy support_messages_update_own on public.support_messages
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists support_messages_update_admin on public.support_messages;
create policy support_messages_update_admin on public.support_messages
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists support_messages_delete_rated_own on public.support_messages;
create policy support_messages_delete_rated_own on public.support_messages
  for delete to authenticated
  using (user_id = (select auth.uid()) and owner_reply is not null and rating is not null);

drop policy if exists support_messages_delete_admin on public.support_messages;
create policy support_messages_delete_admin on public.support_messages
  for delete to authenticated
  using (public.is_admin());

grant select, delete on public.support_messages to authenticated;
grant insert (user_id, subject, message) on public.support_messages to authenticated;
grant update (owner_reply, owner_replied_at) on public.support_messages to authenticated;
grant update (reply_seen_at, rating, rated_at) on public.support_messages to authenticated;
grant usage, select on sequence public.support_messages_message_id_seq to authenticated;

create or replace function public.protect_support_message_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is null or new.user_id is distinct from auth.uid() or public.is_admin() then
      raise exception 'Only a signed-in customer can send a Help Center message.';
    end if;
    select coalesce(nullif(btrim(p.full_name), ''), 'Customer'), p.email
      into new.customer_name, new.customer_email
      from public.profiles p
     where p.id = new.user_id;
    if not found then
      raise exception 'Your customer profile could not be found.';
    end if;
    new.created_at := now();
    new.owner_reply := null;
    new.owner_replied_at := null;
    new.reply_seen_at := null;
    new.rating := null;
    new.rated_at := null;
    return new;
  end if;

  if new.user_id is distinct from old.user_id
     or new.customer_name is distinct from old.customer_name
     or new.customer_email is distinct from old.customer_email
     or new.subject is distinct from old.subject
     or new.message is distinct from old.message
     or new.created_at is distinct from old.created_at then
    raise exception 'A sent customer message cannot be edited.';
  end if;

  if public.is_admin() then
    if new.reply_seen_at is distinct from old.reply_seen_at
       or new.rating is distinct from old.rating
       or new.rated_at is distinct from old.rated_at then
      raise exception 'Only the customer can view or rate the owner reply.';
    end if;
    if new.owner_reply is distinct from old.owner_reply then
      if new.owner_reply is null then
        new.owner_replied_at := null;
      else
        if char_length(btrim(new.owner_reply)) not between 1 and 5000 then
          raise exception 'Replies must be 1 to 5,000 characters.';
        end if;
        new.owner_reply := btrim(new.owner_reply);
        new.owner_replied_at := now();
      end if;
      new.reply_seen_at := null;
      new.rating := null;
      new.rated_at := null;
    elsif new.owner_replied_at is distinct from old.owner_replied_at then
      raise exception 'Reply timestamps are managed by the database.';
    end if;
    return new;
  end if;

  if new.owner_reply is distinct from old.owner_reply
     or new.owner_replied_at is distinct from old.owner_replied_at then
    raise exception 'Only the store owner can reply to customer messages.';
  end if;

  if new.reply_seen_at is distinct from old.reply_seen_at then
    if old.reply_seen_at is not null or old.owner_reply is null or new.reply_seen_at is null then
      raise exception 'This reply cannot be marked as viewed.';
    end if;
    new.reply_seen_at := now();
  end if;

  if new.rating is distinct from old.rating then
    if old.rating is not null or old.reply_seen_at is null or old.owner_reply is null
       or new.rating is null or new.rating not between 1 and 5 then
      raise exception 'View the owner reply before rating it. Ratings can only be submitted once.';
    end if;
    new.rated_at := now();
  elsif new.rated_at is distinct from old.rated_at then
    raise exception 'Rating timestamps are managed by the database.';
  end if;

  return new;
end;
$$;

revoke all on function public.protect_support_message_changes() from public, anon, authenticated;

drop trigger if exists support_messages_protect_changes on public.support_messages;
create trigger support_messages_protect_changes
  before insert or update on public.support_messages
  for each row execute function public.protect_support_message_changes();

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'support_messages'
     ) then
    execute 'alter publication supabase_realtime add table public.support_messages';
  end if;
end;
$$;

notify pgrst, 'reload schema';
commit;
